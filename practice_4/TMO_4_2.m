% Определяем размеры I и J
I = 14; 
J = 21;

% 1. Определение вектора-столбца (случайные числа равномерно распределены)
vector_column = rand(I, 1);  % Вектор-столбец размером Ix1

% 2. Определение вектора-строки (случайные числа равномерно распределены)
vector_row = rand(1, J);  % Вектор-строка размером 1xJ

% 3. Перемножение вектора-столбца и вектора-строки
result_matrix = vector_column * vector_row;  % Результирующая матрица IxJ

% 4. Определение среднего и дисперсии матрицы
mean_value = mean(result_matrix, 'all');  % Среднее всех элементов матрицы
variance_value = var(result_matrix, 0, 'all');  % Дисперсия всех элементов матрицы

% Вывод результатов
fprintf('Среднее значение: %.4f\n', mean_value);
fprintf('Дисперсия: %.4f\n', variance_value);